h = 0
x = 0
books = 0
print("1 - Выдача книги")
print("2 - Просмотр выданных книг")
print("3 - Сброс счётчика")
print("0 - Завершение работы программы")

while h == 0:
    x = 0
    x = int(input("Введите числовой код: "))

    if x == 1:
        books += 1
        print("Книга выдана")
    elif x == 2:
        print(f"Всего книг выдано: {books}")
    elif x == 3:
        books = 0
        print("Количество книг сброшено")
    elif x == 0:
        h = 1
    elif x != 1 and x != 2 and x != 3 and x != 0:
        print("Неизвестная команда")

print("Работа программы завершена")